/**
 * 路由前缀 → PRD key 映射
 *
 * 匹配规则：从当前路由 path 中匹配最长前缀
 * 顺序很重要：越具体的放越前面
 */
const prdMap: Record<string, string> = {
  // 元数据管理
  '/metadata': 'metadata',
  '/asset-management/basic-management/metadata-collection': 'metadata',
  // 数据资产上下架
  '/asset-management/listing-management': 'asset-listing'
  // 其它路径会回退到 default
}

const prdContents: Record<string, string> = {
  default: defaultPrd,
  metadata: metadataPrd,
  'asset-listing': assetListingPrd
}

/**
 * 根据当前路由返回最匹配的 PRD 内容
 * - 先尝试完整前缀
 * - 再逐级去掉最后一段
 * - 都没匹配则用 default
 */
export function getPrdForRoute(routePath: string): string {
  // 去掉 query / hash
  const path = routePath.split('?')[0].split('#')[0]
  // 逐级匹配
  const segments = path.split('/').filter(Boolean)
  while (segments.length > 0) {
    const candidate = '/' + segments.join('/')
    if (prdMap[candidate]) {
      return prdContents[prdMap[candidate]]
    }
    segments.pop()
  }
  return prdContents.default
}

/**
 * 取得当前 PRD 标题（取第一行的 H1 内容）
 * 用于右侧抽屉的标题
 */
export function getPrdTitle(content: string): string {
  const m = /^#\s+(.+)/m.exec(content)
  return m ? m[1].trim() : '产品说明'
}
